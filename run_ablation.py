"""
===============================================================================
AEGIS: ABLATION BENCHMARK EXPERIMENT RUNNER
===============================================================================
Validates whether V-JEPA 2 calibrated spatial parameter embeddings statistically
improve the Julia 2D Cellular Automata hydrodynamic flood simulation against
Copernicus EMSR357 / Sentinel-1 satellite radar ground truth.

Executes a two-arm controlled ablation:
- Arm 1 (Baseline - Physics Only):
    Uniform static soil saturation (0.50) and Manning's roughness (0.035).
    Evaluated over the 100x100 Puri coastal domain grid.
- Arm 2 (V-JEPA 2 Enhanced):
    Spatially heterogeneous 2D parameter grids generated by the calibrated
    PyTorch ParameterProjectionHead from frozen V-JEPA 2 latent embeddings.
    Modulates cell-by-cell numerical diffusion according to geomorphic features.

Outputs:
- Detailed statistical metrics logged to `backtest_ablation_results.json`
- Publication-ready ablation comparison table in terminal
===============================================================================
"""

